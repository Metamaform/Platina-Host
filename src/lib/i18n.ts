import { useState, useEffect } from 'react';
export function useTranslation() {
  const [lang, setLang] = useState(i18n.getLang());
  useEffect(() => {
    return i18n.subscribe(() => setLang(i18n.getLang()));
  }, []);
  return { t: i18n.t, lang, setLang: i18n.setLang };
}
